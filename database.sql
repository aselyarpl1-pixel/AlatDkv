-- Mengaktifkan RLS pada semua tabel
ALTER TABLE alat ENABLE ROW LEVEL SECURITY;
ALTER TABLE peminjaman_alat ENABLE ROW LEVEL SECURITY;

-- Kebijakan untuk tabel alat:
-- - Kunci publik (anon/authenticated): hanya boleh membaca
-- - Kunci rahasia (service_role): bisa baca, tambah, ubah, hapus
CREATE POLICY "publik_baca_alat"
  ON alat FOR SELECT
  TO anon, authenticated
  USING (true);

-- Kebijakan untuk tabel peminjaman_alat:
-- - Kunci publik: TIDAK boleh mengakses sama sekali
-- - Kunci rahasia (service_role): bisa baca, tambah, ubah, hapus
-- (Tidak ada policy untuk anon/authenticated = akses ditolak)
-- Hapus policy default jika ada
DROP POLICY IF EXISTS "publik_akses_peminjaman" ON peminjaman_alat;

