-- Menghapus tabel jika sudah ada (untuk reset)
DROP TABLE IF EXISTS peminjaman_alat CASCADE;
DROP TABLE IF EXISTS alat CASCADE;

-- ============================================================
-- TABEL: alat
-- ============================================================
CREATE TABLE alat (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama        TEXT NOT NULL,
  kategori    TEXT NOT NULL,
  stok        INTEGER NOT NULL DEFAULT 0,
  keterangan  TEXT,
  aktif       BOOLEAN NOT NULL DEFAULT true
);

-- ============================================================
-- TABEL: peminjaman_alat
-- ============================================================
CREATE TABLE peminjaman_alat (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alat_id          BIGINT NOT NULL REFERENCES alat(id) ON DELETE RESTRICT,
  peminjam         TEXT NOT NULL,
  kelas            TEXT NOT NULL,
  keperluan        TEXT NOT NULL,
  jumlah           INTEGER NOT NULL,
  tgl_pinjam       DATE NOT NULL,
  tgl_kembali      DATE NOT NULL,
  status           TEXT NOT NULL DEFAULT 'menunggu',
  alasan_tolak     TEXT,
  kondisi_kembali  TEXT,
  tgl_dikembalikan TIMESTAMPTZ,
  dibuat           TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- ATURAN DI LEVEL BASIS DATA (DB-LEVEL RULES)
-- ============================================================

-- Aturan 1: jumlah alat yang dipinjam harus 1 sampai 5
ALTER TABLE peminjaman_alat
  ADD CONSTRAINT cek_jumlah CHECK (jumlah >= 1 AND jumlah <= 5);

-- Aturan 2: status hanya boleh salah satu dari nilai yang valid
ALTER TABLE peminjaman_alat
  ADD CONSTRAINT cek_status
  CHECK (status IN ('menunggu', 'dipinjam', 'dikembalikan', 'ditolak'));

-- Aturan 3: kondisi kembali hanya boleh nilai yang valid atau kosong
ALTER TABLE peminjaman_alat
  ADD CONSTRAINT cek_kondisi
  CHECK (
    kondisi_kembali IS NULL
    OR kondisi_kembali IN ('baik', 'rusak ringan', 'rusak berat')
  );

-- Aturan 4: tanggal kembali tidak boleh sebelum tanggal pinjam
ALTER TABLE peminjaman_alat
  ADD CONSTRAINT cek_tanggal
  CHECK (tgl_kembali >= tgl_pinjam);

-- Aturan 5: stok alat tidak boleh negatif
ALTER TABLE alat
  ADD CONSTRAINT cek_stok CHECK (stok >= 0);

-- Aturan 6: Trigger untuk mencegah stok alat diturunkan di bawah
-- jumlah unit yang sedang dipinjam (tersedia = stok - dipinjam >= 0)
CREATE OR REPLACE FUNCTION cek_stok_aman()
RETURNS TRIGGER AS $$
DECLARE
  total_dipinjam INTEGER;
BEGIN
  IF NEW.stok IS NOT NULL THEN
    -- Menghitung total unit alat yang sedang dipinjam
    SELECT COALESCE(SUM(jumlah), 0) INTO total_dipinjam
    FROM peminjaman_alat
    WHERE alat_id = NEW.id AND status = 'dipinjam';

    -- Jika stok baru kurang dari yang dipinjam, batalkan
    IF NEW.stok < total_dipinjam THEN
      RAISE EXCEPTION
        'Stok tidak boleh kurang dari jumlah yang sedang dipinjam (%)',
        total_dipinjam;
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_cek_stok_aman
  BEFORE UPDATE OF stok ON alat
  FOR EACH ROW
  EXECUTE FUNCTION cek_stok_aman();

